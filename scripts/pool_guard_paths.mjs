import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {mkdtempSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const pins = JSON.parse(readFileSync(join(root, 'audit/pool-linux-target.json')));
const hash = data => createHash('sha256').update(data).digest('hex');
const rustc = (...args) => execFileSync('rustc', ['+' + pins.rust_release, ...args], {cwd: root, encoding: 'utf8'});
assert(rustc('-vV').split('\n').includes('commit-hash: ' + pins.rust_commit));
const sysroot = rustc('--print', 'sysroot').trim();
for (const [path, digest] of Object.entries(pins.rust_library_sha256)) {
    assert.equal(hash(readFileSync(join(sysroot, 'lib/rustlib/src/rust/library', path))), digest, path);
}

const scratch = mkdtempSync(join(tmpdir(), 'pool-mir-'));
let mir;
try {
    const path = join(scratch, 'locks.mir');
    // The synthetic crate name is part of the pinned compiler fixture.
    rustc('--target', pins.target, '--edition=2024', '--crate-type=lib', '--crate-name', 'pathward_pool_locks',
        '-A', 'dead_code', '-C', 'opt-level=0', '-C', 'panic=unwind', '--emit=mir', '-o', path, 'server/src/pool_locks.rs');
    mir = readFileSync(path, 'utf8');
} finally {
    rmSync(scratch, {recursive: true, force: true});
}
// MIR text is compiler-specific. Review a changed MIR before updating the pin
// or the interpretation of the guard locals and switch branches below.
assert.equal(hash(mir), pins.guard_mir_sha256, 'unreviewed guard MIR');
const blocks = new Map([...mir.matchAll(/^    bb(\d+)(?: \(cleanup\))?: \{\n([\s\S]*?)^    \}/gm)]
    .map(m => [m[1], m[2]]));
const paths = new Set();
function visit(label, trace, visited) {
    assert(!visited.includes(label), 'unexpected loop');
    const body = blocks.get(label);
    assert(body);
    const next = [...trace];
    if (body.includes('as Continue).0: std::sync::MutexGuard')) {
        const guard = body.match(/as Continue\)\.0: std::sync::MutexGuard<'_, ([GH])>/);
        assert(guard, 'unknown guard in success branch');
        next.push(guard[1] === 'G' ? 'takeGeneration' : 'takeHealth');
    }
    if (body.includes('>>::call_once(')) next.push('invoke');
    if (body.includes('drop(_10)')) next.push('dropHealth');
    if (body.includes('drop(_4)')) next.push('dropGeneration');
    if (body.includes('unreachable;')) return;
    if (body.includes('unwind continue')) paths.add([...next,'unwind'].join(' '));
    const edges = [...body.matchAll(/\bbb(\d+)\b/g)].map(m => m[1]);
    if (edges.length === 0) {
        assert(/^\s*(resume|return);/m.test(body), 'unknown terminal');
        next.push(body.includes('resume;') ? 'unwind' : 'returned');
        paths.add(next.join(' '));
    }
    for (const edge of edges) visit(edge, next, [...visited, label]);
}
visit('0', [], []);
const rows = [...paths].sort().map(p => '  [' + p.split(' ').map(e => '.' + e).join(', ') + ']');
const generated = [
    '-- Generated by scripts/pool_guard_paths.mjs from the pinned Rust compiler.',
    'namespace PoolMir', 'inductive Event where',
    '  | takeGeneration | takeHealth | invoke | dropHealth | dropGeneration | returned | unwind',
    '  deriving DecidableEq, Repr', 'def paths : List (List Event) := [',
    rows.join(',\n') + ']', 'end PoolMir', '',
].join('\n');
const output = join(root, 'proofs/Generated/GuardPaths.lean');
if (process.argv.length === 3 && process.argv[2] === '--write') writeFileSync(output, generated);
else {
    assert.equal(process.argv.length, 2);
    assert.equal(readFileSync(output, 'utf8'), generated, 'stale guard paths');
}
console.log('Verified pinned Rust std and ' + paths.size + ' guard paths for ' + pins.target);
